import fs from 'node:fs';
import path from 'node:path';

const envPath = path.resolve(process.cwd(), '.env');
if (fs.existsSync(envPath)) {
  const envContent = fs.readFileSync(envPath, 'utf8');
  envContent.split('\n').forEach((line) => {
    const match = line.match(/^\s*([\w.-]+)\s*=\s*(.*)?\s*$/);
    if (match) {
      const key = match[1];
      let value = match[2] || '';
      if (value.length > 0 && value.startsWith('"') && value.endsWith('"')) {
        value = value.slice(1, -1);
      }
      process.env[key] = value.trim();
    }
  });
}

const OPENAPI_PATH = process.env.OPENAPI_PATH || '../backend/openapi.json';
const OUTPUT_PATH = './shared/constants/gameSystems.generated.ts';

const GENERATED_HEADER = `/**
 * This file was auto-generated by scripts/generate-game-system-badges.mjs.
 * Do not make direct changes to the file.
 */
`;

const PALETTE = [
  '#522626',
  '#1e3a5f',
  '#14532d',
  '#7c2d12',
  '#4c1d95',
  '#0f766e',
  '#9f1239',
  '#1e40af',
  '#854d0e',
  '#365314',
  '#155e75',
  '#6b21a8',
  '#1f2937',
  '#b45309',
  '#3f6212',
  '#0e7490',
];

function djb2(input) {
  let hash = 5381;
  for (let i = 0; i < input.length; i += 1) {
    hash = (hash * 33) ^ input.charCodeAt(i);
  }
  return hash >>> 0;
}

function hexToRgb(hex) {
  const n = Number.parseInt(hex.slice(1), 16);
  return {
    r: (n >> 16) & 255,
    g: (n >> 8) & 255,
    b: n & 255,
  };
}

function contrastText(hex) {
  const { r, g, b } = hexToRgb(hex);
  const luminance = (0.299 * r + 0.587 * g + 0.114 * b) / 255;
  return luminance > 0.55 ? '#000000' : '#ffffff';
}

function toShortLabel(key) {
  return key.replaceAll('_', ' ').toLowerCase();
}

function badgeFor(key) {
  const bgColor = PALETTE[djb2(key) % PALETTE.length];
  return {
    shortLabel: toShortLabel(key),
    bgColor,
    textColor: contrastText(bgColor),
  };
}

try {
  console.log('Генерация каталога бейджей GameSystem...');

  const resolvedOpenapiPath = path.resolve(process.cwd(), OPENAPI_PATH);
  const spec = JSON.parse(fs.readFileSync(resolvedOpenapiPath, 'utf-8'));
  const gameSystemEnum = spec.components?.schemas?.GameSystem?.enum;

  if (!Array.isArray(gameSystemEnum) || gameSystemEnum.length === 0) {
    throw new Error('В OpenAPI не найден components.schemas.GameSystem.enum');
  }

  const entries = gameSystemEnum
    .map((key) => {
      const badge = badgeFor(key);
      return `  ${key}: { shortLabel: '${badge.shortLabel}', bgColor: '${badge.bgColor}', textColor: '${badge.textColor}' },`;
    })
    .join('\n');

  const content = `${GENERATED_HEADER}
import type { GameSystem } from '../open-api/enums';
import type { TBadgeListItem } from '../../components/globals/BadgeList.vue';

export const GAME_SYSTEM_BADGES_GENERATED = {
${entries}
} as const satisfies Record<GameSystem, TBadgeListItem>;
`;

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, content);
  console.log(`Каталог бейджей записан в ${OUTPUT_PATH} (${gameSystemEnum.length} систем)`);
} catch (error) {
  console.error('Ошибка генерации каталога бейджей:', error.message || error);
  process.exit(1);
}
